#   xychart    `xychart-beta` + title / x-axis [..] / y-axis ".." + `bar [..]`


_PIE_SLICE = re.compile(r'^\s*"[^"]*"\s*:\s*(-?[\d.]+)\s*$')
_XY_SERIES = re.compile(r"^\s*(?:bar|line)\s*\[([^\]]*)\]\s*$")
_XY_XAXIS = re.compile(r"^\s*x-axis\s*\[([^\]]*)\]\s*$")
_XY_YAXIS = re.compile(r'^\s*y-axis\s+"([^"]*)"\s*$')
_XY_TITLE = re.compile(r'^\s*title\s+"([^"]*)"\s*$')


def chart_numbers(block: str) -> list[float]:
    out: list[float] = []
    for line in (block or "").splitlines():
        m = _PIE_SLICE.match(line)
        if m:
            out += _floats([m.group(1)])
            continue
        m = _XY_SERIES.match(line)
        if m:
            out += _floats(m.group(1).split(","))
    return out


def _floats(raw: list[str]) -> list[float]:
    out = []
    for piece in raw:
        piece = piece.strip().strip('"')
        try:
            v = float(piece.replace(",", ""))
        except ValueError:
            continue
        if _looks_like_a_year(piece, v):
            continue
        out.append(v)
    return out


def chart_shape(block: str) -> dict:
    lines = [ln for ln in (block or "").strip().splitlines() if ln.strip()]
    head = lines[0].strip() if lines else ""
    shape: dict = {"kind": "", "title": "", "categories": [], "series": 0,
                   "axis": "", "nodes": 0}
    if head.startswith("pie"):
        shape["kind"] = "pie"
        shape["title"] = head[3:].replace("title", "", 1).strip()
        shape["categories"] = [ln.split('"')[1] for ln in lines[1:]
                               if ln.count('"') >= 2 and _PIE_SLICE.match(ln)]
        shape["series"] = 1
        return shape
    if head.startswith("xychart"):
        shape["kind"] = "xy"
        for ln in lines[1:]:
            m = _XY_TITLE.match(ln)
            if m:
                shape["title"] = m.group(1)
            m = _XY_XAXIS.match(ln)
            if m:
                shape["categories"] = [x.strip().strip('"')
                                       for x in m.group(1).split(",") if x.strip()]
            m = _XY_YAXIS.match(ln)
            if m:
                shape["axis"] = m.group(1)
            if _XY_SERIES.match(ln):
                shape["series"] += 1
        return shape
    if head.startswith(("graph", "flowchart")) or head.startswith("---"):
        shape["kind"] = "flow"
        shape["nodes"] = sum(1 for ln in lines if "-->" in ln or "---" in ln) + 1
        return shape
    return shape


_CITE_ANY = re.compile(r"\[[0-9A-Za-z_-]+-\d+-\d+F\d+\]|\[[^\]]{0,40}\]\(note://[^)]+\)")
_CJK_CHAR = re.compile('[\u4e00-\u9fff]')
_SENTENCE = re.compile(r"[^。！？!?\n]+")


ECHO_MIN_CJK = 12
ECHO_MAX_LEN = 200


def echoed_sentence(text: str, before: str = "") -> tuple[str, str] | None:
    for raw in _SENTENCE.findall(text or ""):
        sent = raw.strip()
        if len(sent) < 30 or "|" in sent or (before and sent in before):
            continue
        flat = re.sub(r"\s+", "", _CITE_ANY.sub("　", sent))
        best = ""
        n = len(flat)
        for i in range(n):
            j = i + len(best) + 1
            while j <= n and j - i <= ECHO_MAX_LEN:
                seg = flat[i:j]
                if flat.count(seg) < 2:
                    break
                if len(_CJK_CHAR.findall(seg)) >= ECHO_MIN_CJK and len(seg) > len(best):
                    best = seg
                j += 1
        if best:
            return best, sent
    return None


def drop_echo(text: str, echo: str) -> str:
    if not echo:
        return text
    pat = re.compile(r"\s*".join(re.escape(ch) for ch in echo))
    hits = list(pat.finditer(text or ""))
    if len(hits) < 2:
        return text
    m = hits[1]
    return text[:m.start()] + text[m.end():]


_FACT_ID = re.compile(r"\[([0-9A-Za-z_-]+-\d+-\d+F\d+)\]")


def repeated_citation(text: str, before: str = "") -> tuple[str, str] | None:
    for para in re.split(r"\n\s*\n", text or ""):
        p = para.strip()
        if not p or (before and p in before):
            continue
        ids = _FACT_ID.findall(p)
        dup = [x for x in dict.fromkeys(ids) if ids.count(x) >= 2]
        if dup:
            return dup[0], p
    return None


def drop_repeated_citation(text: str, fid: str) -> str:
    token = f"[{fid}]"
    out = []
    for i, part in enumerate(re.split(r"(\n\s*\n)", text or "")):
        if i % 2 == 0 and part.count(token) >= 2:
            head, _sep, tail = part.partition(token)
            part = head + token + tail.replace(token, "")
        out.append(part)
    return "".join(out)
