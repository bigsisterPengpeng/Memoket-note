import { useEffect, useState } from 'react'
import { friendlyError } from '../util/friendlyError'
import { createNote, digest, memoryScope, SCOPE_LABEL, type MemoryScope, setNoteIcon } from '../api'
import type { Digest } from '../api'
import { toast } from '../toast'
import MarkdownEditor from './MarkdownEditor'
import Icon from './Icon'
import { t } from '../i18n'

const RANGES = [
  { label: 'Last 7 days', days: 7 },   // wrapped in t() at display
  { label: 'Last 30 days', days: 30 },   // wrapped in t() at display
  { label: 'Last 90 days', days: 90 },   // wrapped in t() at display
]

/**
 * Periodic review -- none of the researched competitors ship this cleanly (see
 * [[memoket_note_memory_editor]] research notes: "resurfacing" is flagged as
 * white space, Roam's version is a community hack). Reuses MarkdownEditor in
 * read-only mode so the generated headings/lists render styled instead of
 * as raw markdown text.
 */
export default function DigestPanel() {
  const [result, setResult] = useState<Digest | null>(null)
  // Records "which range is running", not just a boolean — this is an LLM call, not instant;
  // the three buttons used to share one loading boolean, so after clicking "Last 7 days" all three
  // spun together and users couldn't tell which one they clicked.
  const [loading, setLoading] = useState<number | null>(null)
  const [scope, setScope] = useState<MemoryScope>(() => memoryScope())
  useEffect(() => {
    const on = (e: Event) => setScope((e as CustomEvent<MemoryScope>).detail)
    window.addEventListener('memory-scope-changed', on)
    return () => window.removeEventListener('memory-scope-changed', on)
  }, [])
  const scopeLabel = scope === 'all' ? '' : t(SCOPE_LABEL[scope])   // the label already says "only", so the sentence must not repeat it

  // so tell people what's happening and how long they've waited
  const [elapsed, setElapsed] = useState(0)
  useEffect(() => {
    if (loading === null) { setElapsed(0); return }
    const t0 = Date.now()
    const id = setInterval(() => setElapsed(Math.round((Date.now() - t0) / 1000)), 1000)
    return () => clearInterval(id)
  }, [loading])

  const [saving, setSaving] = useState(false)
  async function saveAsNote() {
    if (!result) return
    setSaving(true)
    try {
      const title = t('Review {from} ~ {to}', { from: result.date_from, to: result.date_to })
      const body = `# ${title}\n\n> ${t('Generated by Periodic review · {n} facts', { n: result.fact_count })}\n\n${result.summary.trim()}\n`
      const n = await createNote(title, body)
      await setNoteIcon(n.id, 'bx-history').catch(() => {})     // notes generated by a review get a "history" icon, recognizable on the tree at a glance
      toast(t('Saved as note “{title}”', { title }))
      window.dispatchEvent(new CustomEvent('open-note', { detail: n.id }))
      window.dispatchEvent(new CustomEvent('notes-changed'))
    } catch (e) { toast(t('Could not save note: {err}', { err: friendlyError(e) }), 'error') }
    finally { setSaving(false) }
  }

  async function run(days: number) {
    setLoading(days)
    try { setResult(await digest(days)) }
    catch (e) { toast(t('Review generation failed: {err}', { err: friendlyError(e) }), 'error') }
    finally { setLoading(null) }
  }

  return (
    <div>
      <div className="row" style={{ justifyContent: 'space-between' }}>
        <h2 style={{ margin: 0 }}>{t('Period review')}</h2>
      </div>
      <p className="muted" style={{ fontSize: 'var(--t-sm)', margin: '4px 0 8px' }}>
        {t('Summarizes a period of records into key conclusions / decisions / follow-ups — no digging through records yourself.')}
        {scopeLabel && <>{t('Showing {scope} (change the scope under Related memory in the right pane).', { scope: scopeLabel })}</>}
      </p>
      <div className="row" style={{ flexWrap: 'wrap' }}>
        {RANGES.map((r) => (
          <button key={r.days} onClick={() => run(r.days)} disabled={loading !== null}
                  title={loading !== null ? t('Summarizing the last {n} days; change the range once it finishes', { n: loading }) : undefined}>
            {loading === r.days ? <><span className="spinner" /> {t(r.label)}</> : t(r.label)}
          </button>
        ))}
      </div>
      {loading !== null && (
        <p className="muted" style={{ fontSize: 'var(--t-sm)', margin: '8px 0 0' }}>
          {t('Summarizing the last {n} days into conclusions / decisions / follow-ups — one model call, usually 20–40 s · {sec} s so far', { n: loading, sec: elapsed })}
        </p>
      )}
      {result && (
        <div className="card" style={{ marginTop: 8 }}>
          <div className="row" style={{ alignItems: 'center', gap: 8, margin: '0 0 6px' }}>
            <p className="muted" style={{ fontSize: 'var(--t-sm)', margin: 0 }}>
              {result.date_from} ~ {result.date_to} · {t('{n} facts', { n: result.fact_count })}
            </p>
            <span style={{ flex: 1 }} />
            {/* A review is one-off and gone when the page closes — to keep it, save it as a note, which can later be continued and cited */}
            <button className="chip chip-action" disabled={saving || result.fact_count === 0} title={result.fact_count === 0 ? t('No facts; nothing to save') : undefined} onClick={() => void saveAsNote()}><Icon n="bx-save" /> {t('Save as note')}</button>
          </div>
          <MarkdownEditor content={result.summary} readOnly />
        </div>
      )}
    </div>
  )
}
