/**
 * Icons. **Glyphs come from lucide-react 1.17.0** (the same version and package as memoket desktop 0.5.10,
 * see docs/MEMOKET_DESKTOP_0.5.10.md §3).
 *
 * **The names are still `bx-*`, deliberately.** These names have grown into two places:
 * icons users pick in the icon picker **are stored in the database** (`setNoteIcon`),
 * and mapping tables like `entityIcon` / `noteSource`. Renaming would mean migrating user data,
 * and renaming contributes nothing to "does it look right" — **what changes is the glyphs, not the vocabulary**.
 * So this does just one thing: translate `bx-*` into lucide components.
 *
 * Two decisions that shrink the change surface:
 * - `size="1em"`: the SVG follows `font-size`, so the whole pile of existing sizing CSS like
 *   `.tree-icon .bx { font-size: var(--icon-nav) }` **needs not a single line changed**.
 * - Keep the `bx` class name: those selectors above are written against `.bx` anyway.
 *
 * Stroke width: lucide defaults to 2 (24 viewBox). 0.5.10 uses the default in most places,
 * a few spots tuned to 1.7–2.1. We take the default and pass `strokeWidth` where something thinner is needed.
 */
