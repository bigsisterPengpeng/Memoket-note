export type IconProps = {
  /** A `bx-*` name. The value can come from a constant table or from the database. */
  n: string
  className?: string
  style?: React.CSSProperties
  strokeWidth?: number
  title?: string
}

export default function Icon({ n, className, style, strokeWidth, title }: IconProps) {
  const C = ICONS[n]
  // For unknown names **draw nothing**, rather than leaving a placeholder square:

  if (!C) return null
  return (
    <C className={'bx' + (className ? ' ' + className : '')}
       size="1em" strokeWidth={strokeWidth} style={style} aria-hidden={title ? undefined : true}>
      {title ? <title>{title}</title> : null}
    </C>
  )
}
