import { describe, expect, it } from 'vitest'
import { sourceIcon, sourceLabel } from '../../util/noteSource'

describe('source icons in the tree', () => {
  it('imported and machine-generated notes each have their own icon', () => {
    expect(sourceIcon('feishu')).toBe('bx-paper-plane')
    expect(sourceIcon('plan')).toBe('bx-rocket')
    expect(sourceLabel('plan')).toBe('Generated by endless writing')
  })

  it('notes you wrote have no source icon -- "normal" needs no explanation and should not take a glyph', () => {
    expect(sourceIcon('')).toBe('')
    expect(sourceIcon(undefined)).toBe('')
    expect(sourceLabel('')).toBe('')
  })

  it('unknown sources get no random icon: better the default note than an unreadable symbol', () => {
    expect(sourceIcon('some source that only exists later')).toBe('')
  })

  it('every source with an icon must have an explanation -- an icon that hovering cannot explain is noise', () => {
    for (const s of ['obsidian', 'notion', 'feishu', 'apple', 'evernote', 'import', 'plan']) {
      expect(sourceIcon(s), s).not.toBe('')
      expect(sourceLabel(s), s).not.toBe('')
    }
  })
})

describe('the two "machine-made" kinds that grew in this stretch', () => {
  it('both slides and screen activity digests are recognized', () => {
    // each has its own notes.icon (the user icon wins), so the tree icon shows no difference --
    // **but hovering must say where it came from**, which is exactly sourceLabel's job
    expect(sourceLabel('slides')).toContain('Slides')
    expect(sourceLabel('journey')).toContain('Screen activity')
    expect(sourceIcon('slides')).toBe('bx-slideshow')
  })
})
